              'name': subtopicName,
              'order': 1,
              'isActive': true,
            },
            SetOptions(merge: true),
          );
          batchOperations++;

          questionsRef = subtopicRef.collection('questions');
        } else {
          questionsRef = topicRef.collection('questions');
