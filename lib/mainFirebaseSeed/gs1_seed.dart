        final topicName = row['topic']?.toString().trim() ?? '';
        final subtopicName = row['subtopic']?.toString().trim() ?? '';
        final question = row['question']?.toString().trim() ?? '';

        if (subjectName.isEmpty ||
            topicName.isEmpty ||
            question.isEmpty) {
          print('⚠️ Skipping invalid row: $row');
          continue;
        }

        final subjectId = _createId(subjectName);
        final topicId = _createId(topicName);
        final hasSubtopic = subtopicName.isNotEmpty;
        final subtopicId =
            hasSubtopic ? _createId(subtopicName) : '';

        topicOrders.putIfAbsent(
          subjectId,
          () => <String, int>{},
        );

        final subjectTopicOrders = topicOrders[subjectId]!;

        subjectTopicOrders.putIfAbsent(
          topicId,
          () => subjectTopicOrders.length + 1,
        );

        final subjectRef = subjectsRef.doc(subjectId);

        // --------------------------------------------------------
        // SUBJECT
        // --------------------------------------------------------
        if (!createdSubjects.contains(subjectId)) {
          final subjectOrder =
              subjectOrders[subjectId] ??
              subjectOrders.length + 1;

          await subjectRef.set({
            'name': subjectName,
            'order': subjectOrder,
            'isActive': true,
            'hasSubtopics': subjectId == 'history',
          }, SetOptions(merge: true));

          createdSubjects.add(subjectId);

          print(
            '📚 Subject: $subjectName '
            '(order $subjectOrder)',
          );
        }

        // --------------------------------------------------------
        // TOPIC
        // --------------------------------------------------------
        final topicRef =
            subjectRef.collection('topics').doc(topicId);

        final topicKey = '$subjectId/$topicId';

        if (!createdTopics.contains(topicKey)) {
          await topicRef.set({
            'name': topicName,
            'order': subjectTopicOrders[topicId],
            'isActive': true,
            'hasSubtopics':
                subjectId == 'history' && hasSubtopic,
          }, SetOptions(merge: true));

          createdTopics.add(topicKey);

          print(
            '   📖 Topic: $topicName '
            '(order ${subjectTopicOrders[topicId]})',
          );
        }

        // --------------------------------------------------------
        // QUESTION LOCATION
        // --------------------------------------------------------
        late CollectionReference<Map<String, dynamic>>
            questionsRef;

        if (subjectId == 'history' && hasSubtopic) {
          final subtopicKey =
              '$subjectId/$topicId/$subtopicId';

          final subtopicRef = topicRef
              .collection('subtopics')
              .doc(subtopicId);

          subtopicOrders.putIfAbsent(
            topicKey,
            () => <String, int>{},
          );

          final topicSubtopicOrders =
              subtopicOrders[topicKey]!;

          topicSubtopicOrders.putIfAbsent(
            subtopicId,
            () => topicSubtopicOrders.length + 1,
          );

          if (!createdSubtopics.contains(subtopicKey)) {
            await subtopicRef.set({
              'name': subtopicName,
              'order': topicSubtopicOrders[subtopicId],
              'isActive': true,
            }, SetOptions(merge: true));

            createdSubtopics.add(subtopicKey);

            print(
              '      📌 Subtopic: $subtopicName '
              '(order ${topicSubtopicOrders[subtopicId]})',
            );
          }

          questionsRef =
              subtopicRef.collection('questions');
        } else {
          questionsRef = topicRef.collection('questions');
        }

        // --------------------------------------------------------
        // QUESTION
        // --------------------------------------------------------
        final questionId = _createId(
          '${row['year']}_'
          '${row['questionNumber']}_'
          '${row['order']}',
        );

        final questionRef =
            questionsRef.doc(questionId);

        await questionRef.set({
          'question': question,
          'year': _toInt(row['year']),
          'questionNumber':
              row['questionNumber']?.toString() ?? '',
          'marks': _toDouble(row['marks']),
          'wordLimit': _toInt(row['wordLimit']),
          'order': _toInt(row['order']),
       
          'isActive': true,
        }, SetOptions(merge: true));

        questionCount++;
      }

      print('========================================');
      print('🎉 GS1 Seeder Completed');
      print('Questions: $questionCount');
      print('Subjects: ${createdSubjects.length}');
      print('Topics: ${createdTopics.length}');
      print('Subtopics: ${createdSubtopics.length}');
      print('========================================');
    } catch (e, stackTrace) {
      print('========================================');
      print('❌ GS1 Seeder Failed');
      print('Error: $e');
      print('StackTrace: $stackTrace');
      print('========================================');
    }
  }

  static String _createId(String value) {
    return value
        .toLowerCase()
        .trim()
        .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
        .replaceAll(RegExp(r'^_+|_+$'), '');
  }

  static int _toInt(dynamic value) {
    if (value is int) return value;
    if (value is num) return value.toInt();
    return int.tryParse(value?.toString() ?? '') ?? 0;
  }

  static double _toDouble(dynamic value) {
    if (value is double) return value;
    if (value is num) return value.toDouble();
    return double.tryParse(value?.toString() ?? '') ?? 0;
  }
