        // --------------------------------------------------------
        // QUESTION
        // --------------------------------------------------------

        await questionRef.set({
          'question': question,
          'year': _toInt(row['year']),
          'questionNumber':
              row['questionNumber']?.toString() ?? '',
          'marks': _toDouble(row['marks']),
          'wordLimit': _toInt(row['wordLimit']),
          'order': _toInt(row['order']),
          'isActive': true,
        }, SetOptions(merge: true));

        questionCount++;

        print(
          '      ❓ ${row['questionNumber']} '
          '(${row['year']}) added',
        );
      }

      // ============================================================
      // COMPLETED
      // ============================================================

      print('========================================');
      print('🎉 GS3 Seeder Completed');
      print('Questions: $questionCount');
      print('Subjects: ${createdSubjects.length}');
      print('Topics: ${createdTopics.length}');
      print('Subtopics: 0');
      print('========================================');
    } catch (e, stackTrace) {
      print('========================================');
      print('❌ GS3 Seeder Failed');
      print('Error: $e');
      print('StackTrace: $stackTrace');
      print('========================================');
    }
  }

  // ============================================================
  // CREATE FIRESTORE ID
  // ============================================================

  static String _createId(String value) {
    return value
        .toLowerCase()
        .trim()
        .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
        .replaceAll(RegExp(r'^_+|_+$'), '');
  }

  // ============================================================
  // SAFE INT CONVERSION
  // ============================================================

  static int _toInt(dynamic value) {
    if (value is int) return value;

    if (value is num) {
      return value.toInt();
    }

    return int.tryParse(
          value?.toString() ?? '',
        ) ??
        0;
  }

  // ============================================================
  // SAFE DOUBLE CONVERSION
  // ============================================================

  static double _toDouble(dynamic value) {
    if (value is double) return value;

    if (value is num) {
      return value.toDouble();
    }

    return double.tryParse(
          value?.toString() ?? '',
        ) ??
        0;
  }
