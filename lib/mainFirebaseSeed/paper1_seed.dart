      Future<void> commitBatch() async {
        if (batchOperations == 0) return;
        await batch.commit();
        batch = _firestore.batch();
        batchOperations = 0;
      }

      for (final row in data) {
        final subjectName = row['subject'].toString().trim();
        final topicName = row['topic'].toString().trim();
        final subtopicName = row['subtopic'].toString().trim();

        if (subjectName.isEmpty || topicName.isEmpty) {
          print('⚠️ Skipping invalid row: ${row['questionNumber']}');
          continue;
        }

        final subjectId = _createId(subjectName);
        final topicId = _createId(topicName);
        final hasSubtopic = subtopicName.isNotEmpty;
        final subtopicId =
            hasSubtopic ? _createId(subtopicName) : '';

        if (subjectId.isEmpty || topicId.isEmpty) {
          print('⚠️ Skipping empty ID: ${row['questionNumber']}');
          continue;
        }

        subjectOrders.putIfAbsent(
          subjectId,
          () => subjectOrders.length + 1,
        );

        subjectHasSubtopics[subjectId] =
            (subjectHasSubtopics[subjectId] ?? false) || hasSubtopic;

        topicOrders.putIfAbsent(
          subjectId,
          () => <String, int>{},
        );

        topicOrders[subjectId]!.putIfAbsent(
          topicId,
          () => topicOrders[subjectId]!.length + 1,
        );

        final subjectRef = subjectsRef.doc(subjectId);

        batch.set(
          subjectRef,
          {
            'name': subjectName,
            'order': subjectOrders[subjectId],
            'isActive': true,
            'hasSubtopics': subjectHasSubtopics[subjectId],
          },
          SetOptions(merge: true),
        );
        batchOperations++;

        final topicRef =
            subjectRef.collection('topics').doc(topicId);

        batch.set(
          topicRef,
          {
            'name': topicName,
            'order': topicOrders[subjectId]![topicId],
            'isActive': true,
            'hasSubtopics': hasSubtopic,
          },
          SetOptions(merge: true),
        );
        batchOperations++;

        late CollectionReference<Map<String, dynamic>> questionsRef;

        if (hasSubtopic && subtopicId.isNotEmpty) {
          final subtopicRef =
              topicRef.collection('subtopics').doc(subtopicId);

          batch.set(
            subtopicRef,
            {
              'name': subtopicName,
              'order': 1,
              'isActive': true,
            },
            SetOptions(merge: true),
          );
          batchOperations++;

          questionsRef =
              subtopicRef.collection('questions');
        } else {
          questionsRef =
              topicRef.collection('questions');
        }

        final questionId = _createId(
          '${row['year']}_${row['questionNumber']}_${row['order']}',
        );

        if (questionId.isEmpty) {
          print('⚠️ Skipping empty question ID: ${row['questionNumber']}');
          continue;
        }

        final questionRef = questionsRef.doc(questionId);

        batch.set(
          questionRef,
          {
            'question': row['question'],
            'year': row['year'],
            'questionNumber': row['questionNumber'],
            'marks': row['marks'],
            'wordLimit': row['wordLimit'],
            'order': row['order'],
            'isActive': true,
          },
          SetOptions(merge: true),
        );
        batchOperations++;

        if (batchOperations >= 450) {
          await commitBatch();
        }
      }

      await commitBatch();

      print('========================================');
      print('🎉 PAPER 1 Seeder Completed');
      print('Total Questions: ${data.length}');
      print('Subjects: ${subjectOrders.length}');
